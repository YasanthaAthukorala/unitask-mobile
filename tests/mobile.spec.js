const { test, expect } = require('@playwright/test');
test('students publish paid courses with persistent Sri Lankan provider contacts',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const visibleText=(text,options={})=>page.getByText(text,options).filter({visible:true});
  await page.goto('/home');
  await expect(visibleText('Campus services & courses')).toBeVisible();
  await expect(page.getByRole('button',{name:'Browse services'})).toBeVisible();
  await expect(page.getByRole('button',{name:'View Presentation Slide Design',exact:true})).toBeVisible();
  await page.screenshot({path:'docs/screenshots/home-mobile.png',fullPage:true});

  await page.goto('/explore?category=Photography');
  await expect(visibleText('1 service found',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'View Campus Event Photography'})).toBeVisible();
  await page.getByRole('button',{name:'Category: All',exact:true}).click();
  await page.getByRole('button',{name:'Type: Course',exact:true}).click();
  await expect(visibleText('1 service found',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'View English Conversation Course'})).toBeVisible();

  await page.goto('/explore?category=Programming');
  await expect(visibleText('2 services found',{exact:true})).toBeVisible();
  await page.getByLabel('Search services').fill('Python');
  await expect(visibleText('1 service found',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'View Python Debugging'}).click();
  await expect(visibleText('Rs. 1,500 / hour',{exact:true})).toBeVisible();
  await expect(visibleText('Contact details have not been added to this listing yet.')).toBeVisible();
  await page.getByRole('button',{name:'Save to favorites'}).click();
  await expect(page.getByRole('button',{name:'Remove favorite'})).toBeVisible();
  await page.goto('/profile');
  await expect(page.getByRole('button',{name:'View Python Debugging'})).toBeVisible();

  await page.goto('/create');
  await page.getByLabel('Service or course title',{exact:true}).fill('Java weekend course');
  await page.getByLabel('What you offer',{exact:true}).fill('Four practical Java and OOP classes for campus beginners.');
  await page.getByRole('button',{name:'Course',exact:true}).click();
  await page.getByLabel('Price in LKR',{exact:true}).fill('6000');
  await page.getByRole('button',{name:'Per course',exact:true}).click();
  await page.getByLabel('Availability (optional)',{exact:true}).fill('Saturday mornings, online');
  await page.getByLabel('Service or course title',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'docs/screenshots/create-mobile.png',fullPage:true});

  await page.getByLabel('Provider name',{exact:true}).fill('Campus Java Tutor');
  await page.getByLabel('Contact email',{exact:true}).fill('tutor@example.com');
  await page.getByLabel('Sri Lankan phone number',{exact:true}).fill('077 123 4567');
  await page.getByRole('button',{name:'Save service on this device',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'docs/screenshots/create-contact-mobile.png',fullPage:true});
  await page.getByLabel('Contact email',{exact:true}).fill('invalid-email');
  await page.getByLabel('Sri Lankan phone number',{exact:true}).fill('123');
  await page.getByRole('button',{name:'Save service on this device',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveText('Enter a valid contact email address.');
  await page.getByLabel('Contact email',{exact:true}).fill('tutor@example.com');
  await page.getByRole('button',{name:'Save service on this device',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Enter a Sri Lankan phone number');
  await page.getByLabel('Sri Lankan phone number',{exact:true}).fill('077 123 4567');
  await page.getByRole('button',{name:'Save service on this device',exact:true}).click();
  await expect(page.getByRole('button',{name:'View Java weekend course'})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'View Java weekend course'}).click();
  await expect(visibleText('Rs. 6,000 / course',{exact:true})).toBeVisible();
  await expect(visibleText('Saturday mornings, online',{exact:true})).toBeVisible();
  await expect(visibleText('Campus Java Tutor',{exact:true})).toBeVisible();
  await expect(visibleText('+94771234567',{exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Call provider',exact:true})).toHaveAttribute('href','tel:+94771234567');
  await expect(page.getByRole('link',{name:'Email provider',exact:true})).toHaveAttribute('href',/^mailto:tutor%40example\.com\?subject=/);
  await visibleText('Meet your provider',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'docs/screenshots/provider-contact-mobile.png',fullPage:true});

  await page.getByRole('button',{name:'Edit service',exact:true}).click();
  await expect(page.getByLabel('Contact email',{exact:true})).toHaveValue('tutor@example.com');
  await expect(page.getByLabel('Sri Lankan phone number',{exact:true})).toHaveValue('+94771234567');
  await page.getByLabel('Service or course title',{exact:true}).fill('Updated Java course');
  await page.getByLabel('Sri Lankan phone number',{exact:true}).fill('0112345678');
  await page.getByLabel('Contact email',{exact:true}).fill('updated@example.com');
  await page.getByRole('button',{name:'Update service',exact:true}).click();
  await expect(visibleText('Updated Java course',{exact:true})).toBeVisible();
  await page.reload();
  await expect(visibleText('updated@example.com',{exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Call provider',exact:true})).toHaveAttribute('href','tel:+94112345678');
  await expect(visibleText('Rs. 6,000 / course',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Completed',exact:true}).click();
  await expect(visibleText('Education / Course / Completed',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Delete my service',exact:true}).click();
  await expect(visibleText('No services yet. Share a skill using the Offer tab.')).toBeVisible();

  await page.goto('/explore');
  await expect(visibleText('10 services found',{exact:true})).toBeVisible();
  await visibleText('Learn a skill. Hire campus talent.').scrollIntoViewIfNeeded();
  await page.screenshot({path:'docs/screenshots/explore-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});await page.goto('/home');
  await expect(visibleText('Campus services & courses')).toBeVisible();
  await expect(page.getByRole('button',{name:'View Presentation Slide Design',exact:true})).toBeVisible();
  await page.screenshot({path:'docs/screenshots/home-desktop.png',fullPage:true});
  expect(errors).toEqual([]);
});
