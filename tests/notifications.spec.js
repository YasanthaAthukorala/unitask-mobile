const {test,expect}=require('@playwright/test');
test.use({actionTimeout:20000,navigationTimeout:90000});
test('a student request appears only in the provider local inbox and survives reload',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});page.on('dialog',d=>d.accept());
 let backendCalls=0;
 await page.route('http://127.0.0.1:8000/**',route=>{backendCalls++;return route.abort();});
 const text=value=>page.getByText(value,{exact:true}).filter({visible:true});
 await page.goto('/create');
 await page.getByLabel('Service or course title',{exact:true}).fill('Java course for requests');
 await page.getByLabel('What you offer',{exact:true}).fill('Learn Java with practical weekend classes.');
 await page.getByRole('button',{name:'Course',exact:true}).click();
 await page.getByLabel('Price in LKR',{exact:true}).fill('3000');
 await page.getByRole('button',{name:'Per course',exact:true}).click();
 await page.getByLabel('Provider name',{exact:true}).fill('Java Tutor');
 await page.getByLabel('Contact email',{exact:true}).fill('tutor@example.com');
 await page.getByLabel('Sri Lankan phone number',{exact:true}).fill('0771234567');
 await page.getByRole('button',{name:'Save service on this device',exact:true}).click();
 await page.getByRole('button',{name:'View Java course for requests',exact:true}).click();
 await expect(page.getByRole('button',{name:'Edit service',exact:true})).toBeVisible();
 const servicePath=new URL(page.url()).pathname;
 await expect(page.getByRole('button',{name:'Request course',exact:true})).toHaveCount(0);
 await page.goto('/notifications');await expect(text('No notifications yet.')).toBeVisible();
 await page.goto('/profile');await page.getByRole('button',{name:'Switch local profile',exact:true}).click();
 await page.getByLabel('Profile name',{exact:true}).fill('Java Learner');
 await page.getByLabel('Profile email',{exact:true}).fill('learner@example.com');
 await page.getByLabel('Profile phone',{exact:true}).fill('0771234567');
 await page.getByRole('button',{name:'Create local profile',exact:true}).click();
 await expect(text('Java Learner')).toBeVisible();
 await page.goto(servicePath);
 await page.getByLabel('Interest message',{exact:true}).fill('I would like to join the weekend Java course.');
 await page.getByRole('button',{name:'Request course',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'docs/screenshots/interest-request-mobile.png'});
 await page.getByRole('button',{name:'Request course',exact:true}).click();
 await expect(page.getByText(/Request sent to Java Tutor/).filter({visible:true})).toBeVisible();
 await page.reload();
 await expect(page.getByText(/Request sent to Java Tutor/).filter({visible:true})).toBeVisible();
 await page.goto('/notifications');await expect(text('No notifications yet.')).toBeVisible();
 await page.goto('/profile');await page.getByRole('button',{name:'Switch local profile',exact:true}).click();
 await page.getByRole('button',{name:'Use Me',exact:true}).click();
 await expect(page.getByText('Notifications / 1 unread',{exact:true}).filter({visible:true})).toBeVisible();
 await page.getByRole('button',{name:'Notifications',exact:true}).click();
 await expect(text('Java Learner is interested in "Java course for requests".')).toBeVisible();
 await expect(text('I would like to join the weekend Java course.')).toBeVisible();
 await expect(page.getByRole('link',{name:'Email Java Learner',exact:true})).toHaveAttribute('href','mailto:learner%40example.com');
 await page.screenshot({path:'docs/screenshots/provider-inbox-mobile.png'});
 await page.getByRole('button',{name:'Mark as read',exact:true}).click();
 await expect(text('For Me / 0 unread')).toBeVisible();
 await page.reload();await expect(text('For Me / 0 unread')).toBeVisible();
 await expect(page.getByRole('button',{name:'Mark as read',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'View service',exact:true}).click();
 await expect(text('Java course for requests')).toBeVisible();
 await expect(page.getByRole('button',{name:'Edit service',exact:true})).toBeVisible();
 await page.goto('/profile');await page.getByRole('button',{name:'Switch local profile',exact:true}).click();
 await page.getByRole('button',{name:'Use Java Learner',exact:true}).click();
 await page.goto('/notifications');await expect(text('No notifications yet.')).toBeVisible();
 expect(backendCalls).toBe(0);
 expect(errors).toEqual([]);
});
